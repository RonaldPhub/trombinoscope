DROP DATABASE IF EXISTS membre_message;

CREATE DATABASE IF NOT EXISTS membre_message;
-----------------------------------------------------------------------------

 
 CREATE TABLE IF NOT EXISTS MEMBRE
 (
   CODE_MEMBRE INT(2) NOT NULL AUTO_INCREMENT ,
   PSEUDO VARCHAR(32) NOT NULL  ,
   MAIL VARCHAR(20) NOT NULL DEFAULT '0', 
   MOT_DE_PASSE CHAR(32) NULL  ,
   IS_ADMIN BOOLEAN NULL, 
   DESCRIPTION TEXT NULL, 
   PHOTO LONGBLOB NULL,  
   PRIMARY KEY (CODE_MEMBRE) ,
   UNIQUE INDEX AK_MEMBRE (MAIL) ,
   UNIQUE INDEX AK_MEMBRE1 (PSEUDO) 
 ) ;

CREATE TABLE IF NOT EXISTS MESSAGE
 (
   CODE_MESSAGE INT(2) NOT NULL AUTO_INCREMENT ,
   DE_MEMBRE INT(2) NOT NULL  ,
   A_MEMBRE INT(2) NOT NULL  ,
   MESSAGE TEXT NOT NULL, 
   PRIMARY KEY (CODE_MESSAGE) ,
   FOREIGN KEY (DE_MEMBRE) REFERENCES MEMBRE(CODE_MEMBRE) 
 ) ;


